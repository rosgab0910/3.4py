# Lista com 5 valores numéricos
valores = [10, 5, 23, 7, 15]

# Exibir o maior e o menor valor
print("Maior valor:", max(valores))
print("Menor valor:", min(valores))

# Ordenar a lista
valores_ordenados = sorted(valores)
print("Lista ordenada:", valores_ordenados)

# Mostrar a quantidade de elementos da lista
print("Quantidade de elementos:", len(valores))

# Calcular a média dos valores da lista
media = sum(valores) / len(valores)
print("Média dos valores:", media)
